#include<stdio.h>

// 指定第n位，置0/1 操作
// 例子 给定一个十进制数：13，将它的二进制的第五位改成1，再改成0
// 0000 0000 0000 1101
// 0000 0000 0001 1101
// 0000 0000 0000 1101
int main(){
	int a,n;
	scanf("%d %d",&a,&n);
	// 置 1，其余不变，按位或 1<<(n-1)
	// 0000 0000 0000 1101 // 13
	// 0000 0000 0001 0000
	// 0000 0000 0001 1101 // 29
	a = a|(1<<(n-1));
	printf("%d\n",a);
	// 置 0，其余不变，按位与 ~(1<<(n-1))
	// 0000 0000 0001 1101 // 29
	// 1111 1111 1110 1111
	// 0000 0000 0000 1101 // 13
	a = a & (~(1<<(n-1)));
	printf("%d\n",a);
	return 0;
}
